/// Look up `key` in the zh-CN table, falling back to the key itself
pub fn translate(key: &'static str) -> Cow<'static, str> {
    ZH_CN
        .binary_search_by(|(k, _)| (*k).cmp(key))
        .ok()
        .map(|idx| Cow::Borrowed(ZH_CN[idx].1))
        .unwrap_or(Cow::Borrowed(key))
}
